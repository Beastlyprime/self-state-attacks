#!/usr/bin/env python3
"""
Part A – Task Runner for SELFSTATE v4

Orchestrates real agent trace collection for W1 (Claude Code) and W4 (OpenClaw)
workload profiles. Launches trace_collector.py in the background, runs the agent
task, then stops collection when the task completes.

Usage:
    # Run all W1 sessions (Claude Code on coding tasks)
    python task_runner.py w1 --output-dir traces/W1/

    # Run a single W1 session
    python task_runner.py w1 --session S1 --output-dir traces/W1/

    # Run all W4 sessions (OpenClaw on general assistant tasks)
    python task_runner.py w4 --output-dir traces/W4/

    # Run a single W4 session
    python task_runner.py w4 --session M3 --output-dir traces/W4/

    # Dry-run (print tasks without executing)
    python task_runner.py w1 --dry-run

Prerequisites:
    W1: claude CLI in PATH (claude --print -p "prompt")
    W4: GOOGLE_API_KEY set for Gemini, or --mock flag for scaffold-only runs
    Both: fswatch (macOS) or inotifywait (Linux) for trace collection
"""


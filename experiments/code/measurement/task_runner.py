# Each task's prompt includes the issue's problem_statement.

def _load_swebench_w1_tasks() -> Dict[str, dict]:
    """Load W1 task definitions from SWE-bench verified selection."""
    tasks_file = Path(__file__).parent.parent / "traces" / "swebench_w1_tasks.json"
    if not tasks_file.exists():
        print(f"[ERROR] SWE-bench tasks file not found: {tasks_file}")
        print("Run the SWE-bench issue selection script first.")
        sys.exit(1)

    with open(tasks_file) as f:
        raw = json.load(f)

    tasks = {}
    for key, val in raw.items():
        repo = val["repo"]
        instance_id = val["instance_id"]
        ps = val["problem_statement"]
        tasks[key] = {
            "complexity": val["complexity"],
            "instance_id": instance_id,
            "repo": repo,
            "description": instance_id,
            "prompt": (
                f"Fix the following GitHub issue in the {repo} repository. "
                f"Read the issue description carefully, locate the relevant code, "
                f"and implement a fix.\n\n"
                f"Issue ({instance_id}):\n{ps}"
            ),
            "codebase": repo,
        }
    return tasks



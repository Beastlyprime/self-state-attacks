# ── Trace Collection Orchestrator ───────────────────────────────────

class TraceSession:
    """Manages a single trace collection session."""

    def __init__(self, session_id: str, watch_dirs: List[str],
                 output_dir: Path, profile: str):
        self.session_id = session_id
        self.watch_dirs = watch_dirs
        self.output_dir = output_dir
        self.profile = profile
        self.trace_file = output_dir / f"{session_id}.jsonl"
        self._collector_proc: Optional[subprocess.Popen] = None

    def start_collector(self) -> bool:
        """Start trace_collector.py as a background process."""
        collector_script = Path(__file__).parent / "trace_collector_headless.py"
        if not collector_script.exists():
            # Fall back to workload/trace_collector.py with programmatic control
            collector_script = Path(__file__).parent.parent / "workload" / "trace_collector.py"

        # Use the headless wrapper that doesn't need stdin
        cmd = [
            sys.executable, str(collector_script),
            "--watch-dirs", *self.watch_dirs,
            "--output", str(self.trace_file),
            "--session-tag", self.session_id,
        ]

        try:
            self._collector_proc = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            # Give it time to initialize
            time.sleep(1.0)
            if self._collector_proc.poll() is not None:
                stderr = self._collector_proc.stderr.read()
                print(f"  [WARN] Collector exited early: {stderr[:200]}")
                return False
            return True
        except FileNotFoundError as e:
            print(f"  [ERROR] Cannot start collector: {e}")
            return False

    def stop_collector(self) -> int:
        """Stop the trace collector and return event count."""
        if self._collector_proc and self._collector_proc.poll() is None:
            self._collector_proc.send_signal(signal.SIGINT)
            try:
                self._collector_proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self._collector_proc.kill()
                self._collector_proc.wait()

        # Count events in trace file
        count = 0
        if self.trace_file.exists():
            with open(self.trace_file) as f:
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            evt = json.loads(line)
                            if evt.get("event") not in ("session_start", "session_end"):
                                count += 1
                        except json.JSONDecodeError:
                            pass
        return count


SWEBENCH_REPOS_DIR = Path(__file__).parent.parent / "traces" / "swebench_repos"


def _ensure_swebench_repo(repo: str) -> Path:
    """Clone a SWE-bench repo if not already present. Returns repo path."""
    SWEBENCH_REPOS_DIR.mkdir(parents=True, exist_ok=True)
    repo_dir = SWEBENCH_REPOS_DIR / repo.replace("/", "__")
    if repo_dir.exists():
        return repo_dir

    url = f"https://github.com/{repo}.git"
    print(f"  Cloning {url} ...")
    subprocess.run(
        ["git", "clone", "--depth", "1", url, str(repo_dir)],
        check=True, capture_output=True, text=True,
    )
    return repo_dir


def run_w1_session(session_id: str, task: dict, output_dir: Path,
                   project_dir: str, dry_run: bool = False) -> dict:
    """Run a single W1 (Claude Code) trace collection session.

    All W1 tasks are SWE-bench Verified issues. The task's 'codebase' field
    specifies the GitHub repo (e.g. 'django/django'). The repo is shallow-
    cloned on first use to traces/swebench_repos/<owner>__<repo>/.
    """
    result = {
        "session_id": session_id,
        "profile": "W1",
        "complexity": task["complexity"],
        "description": task["description"],
        "instance_id": task.get("instance_id", ""),
        "repo": task.get("codebase", ""),
        "status": "skipped",
        "n_events": 0,
        "duration_sec": 0,
    }

    if dry_run:
        print(f"  [DRY-RUN] {session_id}: {task['description']} ({task.get('codebase', '')})")
        return result

    print(f"\n{'='*60}")
    print(f"W1 Session {session_id}: {task['description']}")
    print(f"Repo: {task.get('codebase', 'assa-bench')}")
    print(f"Complexity: {task['complexity']}")
    print(f"{'='*60}")

    # Resolve project directory: SWE-bench repo or local project
    codebase = task.get("codebase", "assa-bench")
    if "/" in codebase and codebase != "assa-bench":
        try:
            cwd = str(_ensure_swebench_repo(codebase))
        except subprocess.CalledProcessError as e:
            print(f"  [ERROR] Failed to clone {codebase}: {e.stderr[:200]}")
            result["status"] = "clone_failed"
            return result
    else:
        cwd = project_dir

    # Determine watch directories for Claude Code
    # Claude Code stores state in ~/.claude/projects/<hash>/
    home = os.path.expanduser("~")
    watch_dirs = [
        os.path.join(home, ".claude", "projects"),
        os.path.join(home, ".claude", "settings"),
    ]

    # Also watch project-level .claude/ dir
    project_claude = os.path.join(cwd, ".claude")
    if os.path.isdir(project_claude):
        watch_dirs.append(project_claude)

    session = TraceSession(session_id, watch_dirs, output_dir, "W1")

    # Start collector
    if not session.start_collector():
        result["status"] = "collector_failed"
        return result

    start_time = time.time()

    # Run Claude Code
    try:
        prompt = task["prompt"]
        cmd = ["claude", "--print", "-p", prompt]

        print(f"  Running: claude --print -p '<prompt>' (cwd={cwd})")
        proc = subprocess.run(
            cmd,
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=300,  # 5 min timeout per session
        )

        if proc.returncode != 0:
            print(f"  [WARN] Claude exited with code {proc.returncode}")
            print(f"  stderr: {proc.stderr[:200]}")
            result["status"] = "claude_error"
        else:
            result["status"] = "completed"
            # Print first few lines of output
            output_lines = proc.stdout.strip().split("\n")
            print(f"  Output ({len(output_lines)} lines): {output_lines[0][:80]}...")

    except subprocess.TimeoutExpired:
        print(f"  [WARN] Claude timed out after 300s")
        result["status"] = "timeout"
    except FileNotFoundError:
        print(f"  [ERROR] 'claude' CLI not found in PATH")
        result["status"] = "claude_not_found"

    # Wait a moment for filesystem events to flush
    time.sleep(2.0)

    # Stop collector
    n_events = session.stop_collector()
    duration = time.time() - start_time

    result["n_events"] = n_events
    result["duration_sec"] = round(duration, 2)

    print(f"  Events: {n_events}, Duration: {duration:.1f}s")
    return result


def run_w4_session(session_id: str, task: dict, output_dir: Path,
                   agent_dir: str, dry_run: bool = False,
                   mock: bool = False) -> dict:
    """Run a single W4 (OpenClaw) trace collection session."""
    result = {
        "session_id": session_id,
        "profile": "W4",
        "complexity": task["complexity"],
        "description": task["description"],
        "status": "skipped",
        "n_events": 0,
        "duration_sec": 0,
    }

    if dry_run:
        print(f"  [DRY-RUN] {session_id}: {task['description']}")
        return result

    print(f"\n{'='*60}")
    print(f"W4 Session {session_id}: {task['description']}")
    print(f"Complexity: {task['complexity']}")
    print(f"{'='*60}")

    # Watch the OpenClaw workspace
    workspace_dir = os.path.join(agent_dir, "workspace")
    watch_dirs = [agent_dir]

    session = TraceSession(session_id, watch_dirs, output_dir, "W4")

    # Start collector
    if not session.start_collector():
        result["status"] = "collector_failed"
        return result

    start_time = time.time()

    if mock:
        # Use the workload generator to simulate the session
        result["status"] = _run_w4_mock_session(task, agent_dir)
    else:
        # Use Gemini API to drive the OpenClaw agent
        result["status"] = _run_w4_gemini_session(task, agent_dir)

    # Wait for filesystem events to flush
    time.sleep(2.0)

    # Stop collector
    n_events = session.stop_collector()
    duration = time.time() - start_time

    result["n_events"] = n_events
    result["duration_sec"] = round(duration, 2)

    print(f"  Events: {n_events}, Duration: {duration:.1f}s")
    return result


def _run_w4_gemini_session(task: dict, agent_dir: str) -> str:
    """Drive an OpenClaw session using Gemini API (real agent execution)."""
    api_key = os.environ.get("GOOGLE_API_KEY") or os.environ.get("GEMINI_API_KEY")
    if not api_key:
        print("  [ERROR] GOOGLE_API_KEY or GEMINI_API_KEY not set")
        return "api_key_missing"

    workspace = Path(agent_dir) / "workspace"

    # Build system prompt from identity files
    system_parts = []
    for fname in ["SOUL.md", "AGENTS.md", "IDENTITY.md"]:
        fpath = workspace / fname
        if fpath.exists():
            system_parts.append(fpath.read_text())

    system_prompt = "\n---\n".join(system_parts)

    # Build context from current memory state
    memory_path = workspace / "MEMORY.md"
    memory_content = memory_path.read_text() if memory_path.exists() else ""

    # Load available tools description
    tools_path = workspace / "TOOLS.md"
    tools_content = tools_path.read_text() if tools_path.exists() else ""

    # Compose the full prompt
    full_prompt = (
        f"You are an AI assistant with persistent memory. Your workspace is at {workspace}.\n\n"
        f"## Your Identity\n{system_prompt}\n\n"
        f"## Available Tools\n{tools_content}\n\n"
        f"## Current Memory\n{memory_content}\n\n"
        f"## User Request\n{task['prompt']}\n\n"
        f"## Instructions\n"
        f"Respond to the user's request. If you need to save information to memory, "
        f"write it to {memory_path}. If you need to log your actions, append to "
        f"today's log file. Describe what files you would modify and show the content."
    )

    try:
        import google.generativeai as genai
        genai.configure(api_key=api_key)
        model = genai.GenerativeModel("gemini-2.5-flash")
        response = model.generate_content(full_prompt)

        # Parse the response to determine which files to modify
        response_text = response.text
        print(f"  Gemini response ({len(response_text)} chars)")

        # Apply state changes based on response
        _apply_w4_state_changes(task, response_text, workspace)
        return "completed"

    except ImportError:
        print("  [ERROR] google-generativeai not installed")
        return "import_error"
    except Exception as e:
        print(f"  [ERROR] Gemini API call failed: {e}")
        return "api_error"


def _apply_w4_state_changes(task: dict, response: str, workspace: Path):
    """Apply state changes from Gemini response to workspace files."""
    from datetime import datetime, timezone

    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    daily_log = workspace / "memory" / f"{today}.md"
    memory_path = workspace / "MEMORY.md"

    # Always append to daily log
    log_entry = (
        f"\n## {datetime.now(timezone.utc).strftime('%H:%M')} — "
        f"Task: {task['description']}\n"
        f"Processed user request. Response length: {len(response)} chars.\n"
    )
    with open(daily_log, "a") as f:
        f.write(log_entry)

    # For tasks that expect memory writes, append to MEMORY.md
    expected = task.get("expected_writes", 0)
    if expected > 0 and memory_path.exists():
        # Extract key information from response to save
        # Take first ~200 chars as a reasonable memory entry
        summary = response[:200].replace("\n", " ").strip()
        if summary:
            entry = f"\n- [{today}] {task['description']}: {summary}\n"
            with open(memory_path, "a") as f:
                f.write(entry)

    # For complex tasks, add additional memory entries
    if task["complexity"] == "complex" and memory_path.exists():
        extra_entry = f"- [{today}] Decision: completed {task['description']} task\n"
        with open(memory_path, "a") as f:
            f.write(extra_entry)

    # Heartbeat update
    heartbeat = workspace / "HEARTBEAT.md"
    if heartbeat.exists():
        with open(heartbeat, "w") as f:
            f.write(f"# Heartbeat\nLast active: {datetime.now(timezone.utc).isoformat()}\n"
                    f"Current task: {task['description']}\nStatus: completed\n")


def _run_w4_mock_session(task: dict, agent_dir: str) -> str:
    """Run a mock W4 session using the workload generator (for testing)."""
    project_root = Path(__file__).parent.parent
    sys.path.insert(0, str(project_root))
    from workload.generator_v4 import WorkloadGeneratorV4

    gen = WorkloadGeneratorV4(agent_dir, "W4")

    # Scale ops based on complexity
    ops_map = {"simple": 5, "medium": 10, "complex": 18}
    n_ops = ops_map.get(task["complexity"], 10)

    gen.generate_batch(n_ops=n_ops)
    return "completed_mock"


